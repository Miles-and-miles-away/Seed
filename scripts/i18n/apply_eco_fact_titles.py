def main() -> int:
    with FACTS_PATH.open('r', encoding='utf-8') as fh:
        facts = json.load(fh)

    applied_en = 0
    applied_ja = 0
    applied_es = 0
    missing_en: list[int] = []
    missing_ja: list[int] = []
    missing_es: list[int] = []
    for fact in facts:
        day = fact['dayOfYear']
        title_en = TITLES.get(day)
        if title_en is None:
            missing_en.append(day)
        else:
            fact['nameEn'] = title_en
            applied_en += 1

        title_ja = JA_TITLES.get(day)
        if title_ja is None:
            missing_ja.append(day)
        else:
            fact['nameJa'] = title_ja
            applied_ja += 1

        title_es = ES_TITLES.get(day)
        if title_es is None:
            missing_es.append(day)
        else:
            fact['nameEs'] = fix_diacritics(title_es)
            applied_es += 1

    if missing_en:
        print(f'WARN: no EN titles for days {missing_en}')
    if missing_ja:
        print(f'WARN: no JA titles for days {missing_ja}')
    if missing_es:
        print(f'WARN: no ES titles for days {missing_es}')

    with FACTS_PATH.open('w', encoding='utf-8') as fh:
        json.dump(facts, fh, ensure_ascii=False, indent=2)
        fh.write('\n')
    print(
        f'wrote EN={applied_en} JA={applied_ja} '
        f'ES={applied_es} titles -> {FACTS_PATH}'
    )
    return 0


