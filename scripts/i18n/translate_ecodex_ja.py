def main():
    with open(JSON_PATH, 'r', encoding='utf-8') as f:
        data = json.load(f)

    updated = 0
    missing = []
    for entry in data['entries']:
        eid = entry['id']
        if eid in TRANSLATIONS:
            t = TRANSLATIONS[eid]
            entry['nameJa'] = t['nameJa']
            entry['factJa'] = t['factJa']
            entry['hintJa'] = t['hintJa']
            updated += 1
        else:
            missing.append(eid)

    with open(JSON_PATH, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write('\n')

    print(f'Updated {updated}/100 entries')
    if missing:
        print(f'Missing translations: {missing}')
    else:
        print('All entries translated!')


if __name__ == '__main__':
    main()
