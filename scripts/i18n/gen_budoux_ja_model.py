#!/usr/bin/env python3
"""Vendor the BudouX Japanese phrase model as a Dart constant.

Fetches budoux/models/ja.json and LICENSE at the pinned release tag,
checks the model against its pinned SHA-256, and writes:

- lib/core/utils/ja_phrase_model.g.dart (the model as a const map)
- assets/licences/budoux.txt (shown on the app's licences page)

The pin keeps phrase breaks reproducible: upstream main has since
retrained the model. Bump BUDOUX_TAG and MODEL_SHA256 together, then
run `flutter test test/core/utils/ja_phrase_test.dart`.

Usage: python scripts/i18n/gen_budoux_ja_model.py
"""
from __future__ import annotations

import hashlib
import json
import subprocess
import sys
import urllib.request
from pathlib import Path

BUDOUX_TAG = 'v0.9.3'
MODEL_SHA256 = (
    '580db00a5e3e4a5b99b72cdea0db7ea70dac79599ce9d356d16bfdf0d92e7798'
)
RAW_BASE = f'https://raw.githubusercontent.com/google/budoux/{BUDOUX_TAG}'
COPYRIGHT = 'Copyright 2021 Google LLC'

ROOT = Path(__file__).resolve().parents[2]
DART_OUT = ROOT / 'lib' / 'core' / 'utils' / 'ja_phrase_model.g.dart'
LICENSE_OUT = ROOT / 'assets' / 'licences' / 'budoux.txt'

HEADER = f"""// GENERATED by scripts/i18n/gen_budoux_ja_model.py. Do not edit.
//
// {COPYRIGHT}
// Licensed under the Apache License, Version 2.0; see
// assets/licences/budoux.txt.
//
// Modified from BudouX {BUDOUX_TAG} budoux/models/ja.json: the JSON
// feature tables are restated as a Dart constant.
"""


def fetch(path: str) -> bytes:
    with urllib.request.urlopen(f'{RAW_BASE}/{path}', timeout=30) as resp:
        return resp.read()


def dart_string(value: str) -> str:
    return "'" + value.replace('\\', '\\\\').replace("'", "\\'").replace(
        '$', '\\$') + "'"


def main() -> int:
    raw = fetch('budoux/models/ja.json')
    digest = hashlib.sha256(raw).hexdigest()
    if digest != MODEL_SHA256:
        print(f'ja.json SHA-256 is {digest}, pinned {MODEL_SHA256}')
        return 1
    model: dict[str, dict[str, int]] = json.loads(raw)

    lines = [HEADER, 'const jaPhraseModel = <String, Map<String, int>>{']
    for feature in sorted(model):
        lines.append(f'  {dart_string(feature)}: {{')
        for key, weight in sorted(model[feature].items()):
            lines.append(f'    {dart_string(key)}: {weight},')
        lines.append('  },')
    lines.append('};')
    DART_OUT.parent.mkdir(parents=True, exist_ok=True)
    DART_OUT.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    subprocess.run(['dart', 'format', str(DART_OUT)], check=True)

    license_text = fetch('LICENSE').decode('utf-8')
    LICENSE_OUT.parent.mkdir(parents=True, exist_ok=True)
    LICENSE_OUT.write_text(
        f'BudouX {BUDOUX_TAG} (https://github.com/google/budoux)\n'
        f'{COPYRIGHT}\n\n{license_text}',
        encoding='utf-8',
    )
    weights = sum(len(table) for table in model.values())
    print(f'Wrote {weights} weights to {DART_OUT.relative_to(ROOT)}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
